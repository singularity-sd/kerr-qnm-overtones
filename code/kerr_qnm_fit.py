def light_ring(a):
    """Prograde equatorial circular photon orbit: orbital frequency Omega_c and Lyapunov exponent lambda_c
    (coordinate time)."""
    a = np.asarray(a, dtype=float)
    rc = 2 * (1 + np.cos(2 / 3 * np.arccos(-a)))
    b = 3 * np.sqrt(rc) - a
    delta = rc ** 2 - 2 * rc + a ** 2
    r2 = 2 * (2 * (rc ** 2 + a ** 2 - a * b) + 4 * rc ** 2) - 2 * (b - a) ** 2
    tdot = (rc ** 2 + a ** 2) / delta * (rc ** 2 + a ** 2 - a * b) + a * (b - a)
    return 1 / (rc ** 1.5 + a), np.sqrt(r2 / 2) / tdot


def _corr_universal(p, a, n, l, deg):
    s, L, k = np.sqrt(1 - np.asarray(a, dtype=float)), l + 0.5, deg + 1
    c = [sum(n ** j * (q[j, 0] + q[j, 1] / L + q[j, 2] / L ** 2) for j in range(k))
         for q in (p[3 * k * i:3 * k * (i + 1)].reshape(k, 3) for i in range(3))]
    return 1 + s * (c[0] + c[1] * s) / (1 + c[2] * s)


def _check(l, n, lmin, lmax, nmax):
    n_arr = np.asarray(n)
    if not (lmin <= l <= lmax and np.all((0 <= n_arr) & (n_arr <= nmax))):
        raise ValueError(f"validated only for l = m = {lmin}..{lmax} and n = 0..{nmax}")


def omega_A(a, l, n):
    """Version A (54 numbers): l = m = 2..7, n = 0..4."""
    _check(l, n, 2, 7, 4)
    return l / 2 * _corr_universal(P_A_R, a, n, l, 2) - 1j * (n + 0.5) * light_ring(a)[1] * _corr_universal(P_A_I, a, n, l, 2)


def omega_B(a, l, n):
    """Version B (72 numbers): l = m = 3..7 (validated to 12), n = 0..7."""
    _check(l, n, 3, 12, 7)
    return l / 2 * _corr_universal(P_B_R, a, n, l, 3) - 1j * (n + 0.5) * light_ring(a)[1] * _corr_universal(P_B_I, a, n, l, 3)


def _corr_c(p, a, n):
    s = np.sqrt(1 - np.asarray(a, dtype=float))
    c = [sum(n ** j * q[j] for j in range(4)) for q in p.reshape(5, 4)]
    return 1 + s * (c[0] + c[1] * s + c[2] * s ** 2) / (1 + c[3] * s + c[4] * s ** 2)


def omega_C(a, n):
    """Version C (40 numbers): l = m = 2, n = 0..4."""
    _check(2, n, 2, 2, 4)
    return _corr_c(P_C_R, a, n) - 1j * (n + 0.5) * light_ring(a)[1] * _corr_c(P_C_I, a, n)


